import AVFoundation
import Combine
import Foundation
import UIKit

@MainActor
final class AVSpeechAudioCoach: NSObject, AudioCoach, AVSpeechSynthesizerDelegate {
    private struct PendingSpeech {
        let utterance: AVSpeechUtterance
        let isAutomaticPulse: Bool
        let requestedAt: TimeInterval
    }

    private var synthesizer = AVSpeechSynthesizer()
    private let voice = AVSpeechSynthesisVoice(language: "en-GB")
    private var observers = Set<AnyCancellable>()
    private var isInterrupted = false
    private var coachingActive = false
    private var deactivateWhenFinished = false
    private let audioSessionQueue = DispatchQueue(label: "AudioCoach.audioSession", qos: .userInitiated)
    private var isAudioSessionActive = false
    private var activationID: UUID?
    private var pendingUtterances: [PendingSpeech] = []
    private var submittedUtterances = Set<ObjectIdentifier>()
    private var currentUtteranceID: ObjectIdentifier?
    private var speechStartCheckID: UUID?
    private var speechDeadline: TimeInterval?
    private var speechBackgroundTask: UIBackgroundTaskIdentifier = .invalid
    private var backgroundTaskRequestID: UUID?

    override init() {
        super.init()
        synthesizer.delegate = self
        // Use our configured playback session for locked-screen speech.
        synthesizer.usesApplicationAudioSession = true
        NotificationCenter.default.publisher(for: AVAudioSession.interruptionNotification)
            .sink { [weak self] notification in
                let type = notification.userInfo?[AVAudioSessionInterruptionTypeKey] as? UInt
                let options = notification.userInfo?[AVAudioSessionInterruptionOptionKey] as? UInt ?? 0
                let reason = notification.userInfo?[AVAudioSessionInterruptionReasonKey] as? UInt
                DispatchQueue.main.async { [weak self] in
                    self?.handleInterruption(type: type, options: options, reason: reason)
                }
            }
            .store(in: &observers)
        NotificationCenter.default.publisher(for: AVAudioSession.mediaServicesWereResetNotification)
            .sink { [weak self] _ in
                DispatchQueue.main.async { [weak self] in
                    self?.recoverAudio(reason: "media services reset")
                }
            }
            .store(in: &observers)
        NotificationCenter.default.publisher(for: UIApplication.didBecomeActiveNotification)
            .sink { [weak self] _ in
                DispatchQueue.main.async { [weak self] in
                    guard let self, !self.isInterrupted,
                          self.coachingActive || self.isAudioSessionActive || self.activationID != nil else { return }
                    self.ensureAudioReady(reason: "app became active")
                }
            }
            .store(in: &observers)
        NotificationCenter.default.publisher(for: AVAudioSession.routeChangeNotification)
            .sink { [weak self] notification in
                let reason = notification.userInfo?[AVAudioSessionRouteChangeReasonKey] as? UInt
                DispatchQueue.main.async { [weak self] in
                    guard let self, !self.isInterrupted,
                          self.coachingActive || self.isAudioSessionActive,
                          let reason, let change = AVAudioSession.RouteChangeReason(rawValue: reason) else { return }
                    // Ignore category changes generated by our own activation.
                    switch change {
                    case .noSuitableRouteForCategory:
                        self.recoverAudio(reason: "audio route changed (\(reason))")
                    case .newDeviceAvailable, .oldDeviceUnavailable, .routeConfigurationChange:
                        self.ensureAudioReady(reason: "audio route changed (\(reason))")
                    default:
                        break
                    }
                }
            }
            .store(in: &observers)
    }

    /// Allows background speech; Bluetooth notifications provide execution between cues.
    func activate() {
        coachingActive = true
        deactivateWhenFinished = false
        configureAudioSession()
    }

    private func configureAudioSession() {
        guard !isInterrupted, !isAudioSessionActive, activationID == nil else { return }
        beginSpeechBackgroundTask()
        let requestID = UUID()
        activationID = requestID
        // Category changes and setActive can block. Keep them off the main actor,
        // and serialize activation/deactivation so a rapid restart stays ordered.
        audioSessionQueue.async { [weak self] in
            let failure: String?
            do {
                let audioSession = AVAudioSession.sharedInstance()
                try audioSession.setCategory(.playback, mode: .default, options: .mixWithOthers)
                try audioSession.setActive(true)
                failure = nil
            } catch {
                failure = error.localizedDescription
            }
            DispatchQueue.main.async { [weak self] in
                self?.didActivateAudioSession(requestID: requestID, failure: failure)
            }
        }
    }

    private func didActivateAudioSession(requestID: UUID, failure: String?) {
        // An interruption or media-services reset invalidates older completions.
        guard activationID == requestID else { return }
        activationID = nil
        if let failure {
            pendingUtterances.removeAll()
            print("🔊 Audio session activation failed: \(failure)")
            deactivateWhenFinished = false
            endSpeechBackgroundTask()
            return
        }
        isAudioSessionActive = true
        NSLog("🔊 Audio session activated")
        let utterances = pendingUtterances
        pendingUtterances.removeAll()
        for speech in utterances {
            // Do not speak an old pulse if session activation was slow.
            if speech.isAutomaticPulse && ProcessInfo.processInfo.systemUptime - speech.requestedAt >= 5 {
                NSLog("🔊 Automatic pulse discarded: activation took too long")
                continue
            }
            submit(speech.utterance)
        }
        deactivateIfFinished()
    }

    func deactivate() {
        coachingActive = false
        // Include speech waiting for activation, not just speech already playing.
        deactivateWhenFinished = true
        deactivateIfFinished()
    }

    private func deactivateIfFinished() {
        guard activationID == nil,
              pendingUtterances.isEmpty, submittedUtterances.isEmpty,
              !synthesizer.isSpeaking, !synthesizer.isPaused else { return }
        endSpeechBackgroundTask()
        if deactivateWhenFinished { deactivateAudioSession() }
    }

    private func deactivateAudioSession() {
        deactivateWhenFinished = false
        guard isAudioSessionActive || activationID != nil else { return }
        activationID = nil
        isAudioSessionActive = false
        audioSessionQueue.async {
            do {
                try AVAudioSession.sharedInstance().setActive(false, options: .notifyOthersOnDeactivation)
            } catch {
                print("🔊 Audio session deactivation failed: \(error.localizedDescription)")
            }
        }
    }

    func speak(_ message: String, settings: AppSettings) {
        requestSpeech(message, settings: settings, isAutomaticPulse: false)
    }

    func speakAutomaticPulse(_ message: String, settings: AppSettings) {
        requestSpeech(message, settings: settings, isAutomaticPulse: true)
    }

    private func requestSpeech(_ message: String, settings: AppSettings, isAutomaticPulse: Bool) {
        guard settings.audioEnabled, !isInterrupted else { return }
        // Timers may not run while suspended. Check the deadline on the next
        // Bluetooth-driven announcement too, before accepting any new speech.
        if let speechDeadline, ProcessInfo.processInfo.systemUptime >= speechDeadline {
            recoverAudio(reason: "stalled speech detected on a new request")
        }
        let busy = activationID != nil || !pendingUtterances.isEmpty || !submittedUtterances.isEmpty
            || synthesizer.isSpeaking || synthesizer.isPaused
        if isAutomaticPulse && busy {
            NSLog("🔊 Automatic pulse discarded: '\(message)' (speech busy)")
            return
        }
        // Instructions arriving during activation supersede any waiting pulse.
        if !isAutomaticPulse { pendingUtterances.removeAll(where: { $0.isAutomaticPulse }) }
        beginSpeechBackgroundTask()

        let utterance = AVSpeechUtterance(string: message)
        utterance.voice = voice
        utterance.rate = Float(settings.voiceRate)
        NSLog("🔊 Speech requested: '\(message)' | Rate: \(utterance.rate) | Busy: \(!submittedUtterances.isEmpty)")
        if isAudioSessionActive {
            submit(utterance)
        } else {
            pendingUtterances.append(PendingSpeech(utterance: utterance,
                                                  isAutomaticPulse: isAutomaticPulse,
                                                  requestedAt: ProcessInfo.processInfo.systemUptime))
            configureAudioSession()
        }
    }

    private func ensureAudioReady(reason: String) {
        guard !isInterrupted else { return }
        if let speechDeadline, ProcessInfo.processInfo.systemUptime >= speechDeadline {
            recoverAudio(reason: "\(reason): stalled playback")
        } else if !isAudioSessionActive {
            configureAudioSession()
        }
        // Healthy playback must not be interrupted merely by unlocking the phone.
    }

    private func submit(_ utterance: AVSpeechUtterance) {
        submittedUtterances.insert(ObjectIdentifier(utterance))
        synthesizer.speak(utterance)
        checkForStalledSpeech()
    }

    private func checkForStalledSpeech() {
        guard !submittedUtterances.isEmpty,
              speechStartCheckID == nil else { return }
        let checkID = UUID()
        speechStartCheckID = checkID
        let now = ProcessInfo.processInfo.systemUptime
        if speechDeadline == nil { speechDeadline = now + 5 }
        let delay = max(0, (speechDeadline ?? now) - now)
        DispatchQueue.main.asyncAfter(deadline: .now() + delay) { [weak self] in
            guard let self, self.speechStartCheckID == checkID,
                  !self.submittedUtterances.isEmpty else { return }
            // AVSpeechSynthesizer has no audio-queue-error delegate callback.
            // Check both missing starts and missing finishes; never replay stale cues.
            self.recoverAudio(reason: self.currentUtteranceID == nil
                ? "speech did not start within 5 seconds"
                : "speech did not finish before its deadline")
        }
    }

    private func beginSpeechBackgroundTask() {
        guard speechBackgroundTask == .invalid else { return }
        let requestID = UUID()
        backgroundTaskRequestID = requestID
        // A Bluetooth wake is brief. Keep activation and its speech callbacks
        // alive, but release the assertion as soon as this batch finishes.
        speechBackgroundTask = UIApplication.shared.beginBackgroundTask(withName: "AudioCoach.speech") { [weak self] in
            DispatchQueue.main.async { [weak self] in
                guard let self, self.backgroundTaskRequestID == requestID else { return }
                self.endSpeechBackgroundTask()
                let deadlineExpired = self.speechDeadline.map {
                    ProcessInfo.processInfo.systemUptime >= $0
                } ?? false
                if self.synthesizer.isSpeaking && !self.synthesizer.isPaused && !deadlineExpired {
                    // Actual playback uses the declared audio background mode;
                    // expiration of this temporary assertion is not an audio failure.
                    NSLog("🔊 Speech background time expired; leaving active playback running")
                    return
                }
                NSLog("🔊 Speech background time expired without healthy playback; discarding queued speech")
                self.stop()
                self.deactivateAudioSession()
            }
        }
        if speechBackgroundTask == .invalid { backgroundTaskRequestID = nil }
    }

    private func endSpeechBackgroundTask() {
        guard speechBackgroundTask != .invalid else { return }
        let task = speechBackgroundTask
        speechBackgroundTask = .invalid
        backgroundTaskRequestID = nil
        UIApplication.shared.endBackgroundTask(task)
    }

    private func recoverAudio(reason: String) {
        NSLog("🔊 Recovering audio: \(reason); discarding queued speech")
        activationID = nil
        isAudioSessionActive = false
        pendingUtterances.removeAll()
        submittedUtterances.removeAll()
        currentUtteranceID = nil
        speechStartCheckID = nil
        speechDeadline = nil
        synthesizer.delegate = nil
        synthesizer.stopSpeaking(at: .immediate)
        synthesizer = AVSpeechSynthesizer()
        synthesizer.delegate = self
        synthesizer.usesApplicationAudioSession = true
        // Clear the stale session before reactivating, on the same serial queue.
        if !isInterrupted {
            audioSessionQueue.async {
                do {
                    try AVAudioSession.sharedInstance().setActive(false, options: .notifyOthersOnDeactivation)
                } catch {
                    print("🔊 Audio recovery deactivation failed: \(error.localizedDescription)")
                }
            }
            if coachingActive { configureAudioSession() }
        }
        deactivateIfFinished()
    }

    func stop() {
        pendingUtterances.removeAll()
        submittedUtterances.removeAll()
        currentUtteranceID = nil
        speechStartCheckID = nil
        speechDeadline = nil
        synthesizer.stopSpeaking(at: .immediate)
        deactivateIfFinished()
    }

    private func handleInterruption(type: UInt?, options: UInt, reason: UInt?) {
        guard let type, let interruption = AVAudioSession.InterruptionType(rawValue: type) else { return }
        switch interruption {
        case .began:
            // Modern iOS no longer emits app-suspension interruptions.
            // Do not mistake an actual audio interruption for a suspension.
            isInterrupted = true
            activationID = nil
            isAudioSessionActive = false
            // Drop stale cues instead of replaying workout instructions after a call.
            stop()
            endSpeechBackgroundTask()
            NSLog("🔊 Audio interrupted; reason: %@", reason.map { String($0) } ?? "unspecified")
        case .ended:
            isInterrupted = false
            let shouldResume = AVAudioSession.InterruptionOptions(rawValue: options).contains(.shouldResume)
            if coachingActive && shouldResume { configureAudioSession() }
            print("🔊 Audio interruption ended; should resume: \(shouldResume)")
        @unknown default:
            break
        }
    }

    // MARK: - AVSpeechSynthesizerDelegate

    nonisolated func speechSynthesizer(_ synthesizer: AVSpeechSynthesizer,
                                      didStart utterance: AVSpeechUtterance) {
        let utteranceID = ObjectIdentifier(utterance)
        let message = utterance.speechString
        // Generous upper bound accommodates slower voices and longer instructions.
        let rateAdjustment = max(1, Double(AVSpeechUtteranceDefaultSpeechRate) / Double(max(utterance.rate, 0.05)))
        let finishTimeout = max(30, Double(message.split(whereSeparator: { $0.isWhitespace }).count) * 2 * rateAdjustment)
        DispatchQueue.main.async { [weak self] in
            guard let self, self.submittedUtterances.contains(utteranceID) else { return }
            self.currentUtteranceID = utteranceID
            self.speechStartCheckID = nil
            self.speechDeadline = ProcessInfo.processInfo.systemUptime + finishTimeout
            self.checkForStalledSpeech()
            NSLog("🔊 Speech started: '\(message)'")
        }
    }

    nonisolated func speechSynthesizer(_ synthesizer: AVSpeechSynthesizer,
                                      didPause utterance: AVSpeechUtterance) {
        let utteranceID = ObjectIdentifier(utterance)
        DispatchQueue.main.async { [weak self] in
            guard let self, !self.isInterrupted, self.synthesizer.isPaused else { return }
            guard self.submittedUtterances.contains(utteranceID) else { return }
            self.synthesizer.continueSpeaking()
        }
    }

    nonisolated func speechSynthesizer(_ synthesizer: AVSpeechSynthesizer,
                                      didFinish utterance: AVSpeechUtterance) {
        let utteranceID = ObjectIdentifier(utterance)
        let message = utterance.speechString
        DispatchQueue.main.async { [weak self] in
            guard let self, self.submittedUtterances.contains(utteranceID) else { return }
            self.submittedUtterances.remove(utteranceID)
            if self.currentUtteranceID == utteranceID || self.currentUtteranceID == nil {
                self.currentUtteranceID = nil
                self.speechStartCheckID = nil
                self.speechDeadline = nil
            }
            NSLog("🔊 Speech finished: '\(message)'")
            self.checkForStalledSpeech()
            self.deactivateIfFinished()
        }
    }

    nonisolated func speechSynthesizer(_ synthesizer: AVSpeechSynthesizer,
                                      didCancel utterance: AVSpeechUtterance) {
        let utteranceID = ObjectIdentifier(utterance)
        DispatchQueue.main.async { [weak self] in
            guard let self, self.submittedUtterances.contains(utteranceID) else { return }
            self.submittedUtterances.remove(utteranceID)
            if self.currentUtteranceID == utteranceID || self.currentUtteranceID == nil {
                self.currentUtteranceID = nil
                self.speechStartCheckID = nil
                self.speechDeadline = nil
            }
            self.checkForStalledSpeech()
            self.deactivateIfFinished()
        }
    }
}
